const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');
const { execFileSync } = require('node:child_process');
const sharp = require('sharp');

const ROOT = path.resolve(__dirname, '..');
const OUT = path.join(ROOT, 'dist');

const EXCLUDED_TOP = new Set(['.github', 'docs', 'scripts', 'tests', 'worker', 'migrations', 'node_modules', 'dist']);
const EXCLUDED_FILES = new Set([
  '.gitignore',
  'package.json',
  'package-lock.json',
  'wrangler.jsonc',
  'vercel.json',
  'netlify.toml'
]);

function trackedFiles() {
  const output = execFileSync('git', ['ls-files', '-z'], { cwd: ROOT });
  return output.toString('utf8').split('\0').filter(Boolean);
}

function shouldPublish(rel) {
  const normalized = rel.replaceAll('\\', '/');
  const parts = normalized.split('/');
  if (EXCLUDED_TOP.has(parts[0])) return false;
  if (EXCLUDED_FILES.has(normalized)) return false;
  if (/^(?:\.env(?:\..*)?|\.dev\.vars(?:\..*)?)$/i.test(path.posix.basename(normalized))) return false;
  if (/\.md$/i.test(normalized)) return false;
  return true;
}

function copyTrackedFile(rel) {
  const src = path.join(ROOT, rel);
  const dest = path.join(OUT, rel);
  const stat = fs.statSync(src);
  if (!stat.isFile()) return;
  fs.mkdirSync(path.dirname(dest), { recursive: true });
  fs.copyFileSync(src, dest);
}

function assertExists(rel) {
  const target = path.join(OUT, rel);
  if (!fs.existsSync(target) || !fs.statSync(target).isFile()) {
    throw new Error(`Cloudflare build missing required file: ${rel}`);
  }
}

function normalizeHref(href) {
  const clean = String(href || '').split('#')[0].split('?')[0].replace(/^\/+/, '');
  try { return decodeURIComponent(clean); } catch { return clean; }
}

function sanitizeCloudflareArtifact() {
  const basePath = path.join(OUT, 'index_base.html');
  let html = fs.readFileSync(basePath, 'utf8');
  html = html.replace(/\s*<script\b[^>]*src=["']\/_vercel\/insights\/script\.js["'][^>]*><\/script>/gi, '');
  fs.writeFileSync(basePath, html, 'utf8');
  if (html.includes('/_vercel/')) {
    throw new Error('Cloudflare artifact still contains a Vercel-only /_vercel/ runtime path.');
  }
}

function shortHash(filePath) {
  return crypto.createHash('sha256').update(fs.readFileSync(filePath)).digest('hex').slice(0, 12);
}

async function optimizeCatalogCovers(catalog) {
  let originalBytes = 0;
  let optimizedBytes = 0;
  let optimizedCount = 0;

  for (const game of Array.isArray(catalog.games) ? catalog.games : []) {
    const rawCover = normalizeHref(game.cover || '');
    if (!rawCover.startsWith('assets/gate-image/')) continue;
    if (!/\.(?:png|jpe?g)$/i.test(rawCover)) continue;

    const sourcePath = path.join(ROOT, rawCover);
    if (!fs.existsSync(sourcePath)) continue;

    const webpRel = rawCover.replace(/\.(?:png|jpe?g)$/i, '.webp');
    const webpPath = path.join(OUT, webpRel);
    fs.mkdirSync(path.dirname(webpPath), { recursive: true });

    await sharp(sourcePath)
      .resize({ width: 960, height: 540, fit: 'cover', position: 'centre', withoutEnlargement: true })
      .webp({ quality: 82, effort: 4, smartSubsample: true })
      .toFile(webpPath);

    const sourceSize = fs.statSync(sourcePath).size;
    const webpSize = fs.statSync(webpPath).size;
    originalBytes += sourceSize;
    optimizedBytes += webpSize;
    optimizedCount += 1;

    game.cover = `${webpRel}?v=${shortHash(sourcePath)}`;
  }

  fs.writeFileSync(path.join(OUT, 'data/games.json'), `${JSON.stringify(catalog, null, 2)}\n`, 'utf8');
  return { optimizedCount, originalBytes, optimizedBytes };
}

function writeStaticHeaders() {
  const headers = `# Generated by scripts/build-cloudflare.cjs\n/assets/*\n  Cache-Control: public, max-age=86400, stale-while-revalidate=604800\n\n/assets/gate-image/*.webp\n  Cache-Control: public, max-age=31536000, immutable\n\n`;
  fs.writeFileSync(path.join(OUT, '_headers'), headers, 'utf8');
}

function formatMiB(bytes) {
  return `${(bytes / 1024 / 1024).toFixed(2)} MiB`;
}

async function main() {
  fs.rmSync(OUT, { recursive: true, force: true });
  fs.mkdirSync(OUT, { recursive: true });

  const tracked = trackedFiles();
  const sourceFiles = tracked.filter(shouldPublish);
  sourceFiles.forEach(copyTrackedFile);

  assertExists('index.html');
  assertExists('index_base.html');
  assertExists('data/games.json');
  sanitizeCloudflareArtifact();

  const catalogPath = path.join(OUT, 'data/games.json');
  const catalog = JSON.parse(fs.readFileSync(catalogPath, 'utf8'));
  const coverStats = await optimizeCatalogCovers(catalog);
  writeStaticHeaders();

  const enabledGames = Array.isArray(catalog.games) ? catalog.games.filter(game => !game.disabled) : [];
  for (const game of enabledGames) {
    const rel = normalizeHref(game.href);
    if (!rel) throw new Error(`Enabled game has no href: ${game.id || game.title || 'unknown'}`);
    assertExists(rel);
  }

  for (const forbidden of ['.github', 'docs', 'scripts', 'tests', 'worker', 'migrations']) {
    if (fs.existsSync(path.join(OUT, forbidden))) {
      throw new Error(`Development/server directory leaked into dist: ${forbidden}`);
    }
  }

  const secretNames = tracked.filter(rel => /(^|\/)(?:\.env(?:\..*)?|\.dev\.vars(?:\..*)?)$/i.test(rel));
  if (secretNames.length) {
    throw new Error(`Secret environment files are tracked and must not be deployed: ${secretNames.join(', ')}`);
  }

  const savedBytes = Math.max(0, coverStats.originalBytes - coverStats.optimizedBytes);
  const savedPct = coverStats.originalBytes > 0 ? Math.round(savedBytes / coverStats.originalBytes * 100) : 0;

  console.log('Kidscade Cloudflare build complete');
  console.log(`- published tracked files: ${sourceFiles.length}`);
  console.log(`- enabled game entry files verified: ${enabledGames.length}`);
  console.log(`- optimized cover images: ${coverStats.optimizedCount}`);
  if (coverStats.optimizedCount) {
    console.log(`- cover payload: ${formatMiB(coverStats.originalBytes)} -> ${formatMiB(coverStats.optimizedBytes)} (${savedPct}% smaller)`);
  }
  console.log('- immutable cover caching with source-hash URLs: enabled');
  console.log('- Worker/D1 source excluded from public dist: yes');
  console.log('- Vercel-only runtime path stripped: yes');
  console.log(`- output: ${path.relative(ROOT, OUT)}/`);
}

main().catch(error => {
  console.error(error?.stack || error);
  process.exitCode = 1;
});
